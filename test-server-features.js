// Server panel features: modpack server with client-only mods skipped, Geyser, properties, backups, players, auto-restart. Run: npm run test:server
const assert = require('assert'), fs = require('fs'), path = require('path')
const tmp = fs.mkdtempSync(path.join(require('os').tmpdir(), 'mm4-'))
const core = require('./core')(path.join(tmp, 'profiles'), { emit: () => {} })
const wait = async (fn, s = 180) => { for (let i = 0; i < s; i++) { if (await fn()) return true; await new Promise(r => setTimeout(r, 1000)) } return false }
;(async () => {
  let p = await core.createProfile({ name: 'Pack', type: 'modrinth', mc: { version: '1.21.1', loader: 'fabric' } })
  const pack = (await core.search(p.id, 'modrinth', 'fabulously optimized', 1, { kind: 'modpack' })).items[0]
  p = await core.install(p.id, 'modrinth', pack.id)
  p = await core.install(p.id, 'modrinth', 'gvQqBUqZ') // Lithium (server+client)

  await core.setServerProps(p.id, { motd: 'Hello friends', difficulty: 'hard', 'max-players': 5, evil: 'x' })
  await core.serverStart(p.id, { eula: true, port: 25633, geyser: true, autoRestart: true })
  assert(await wait(async () => (await core.serverStatus(p.id)).online, 240), 'online: ' + (await core.serverStatus(p.id)).log.slice(-8).join('\n'))
  const mods = fs.readdirSync(path.join(tmp, 'profiles', p.id, 'server/mods'))
  assert(mods.some(f => /lithium/i.test(f)) && mods.some(f => /geyser/i.test(f)) && mods.some(f => /floodgate/i.test(f)), 'mods: ' + mods)
  assert(!mods.some(f => /sodium|iris|modmenu/i.test(f)), 'client-only pack mods skipped: ' + mods)
  const props = core.serverProps(p.id)
  assert(props.motd === 'Hello friends' && props.difficulty === 'hard' && !props.evil && props['server-port'] === '25633', 'props')
  assert((await core.serverStatus(p.id)).bedrock, 'bedrock address')
  const name = await core.backup(p.id)
  assert((await core.backups(p.id)).some(b => b.name === name), 'backup listed')
  core.playerAction(p.id, 'op', 'Notch'); core.playerAction(p.id, 'allow', 'Notch')
  assert.throws(() => core.playerAction(p.id, 'op', 'bad name;stop'), /Invalid/)
  await wait(async () => core.serverPlayers(p.id).ops.includes('Notch') && core.serverPlayers(p.id).whitelist.includes('Notch'), 20)
  assert(core.serverPlayers(p.id).ops.includes('Notch'), 'op via console: ' + JSON.stringify(core.serverPlayers(p.id)))
  // Crash -> auto restart
  process.kill((await new Promise(r => r(require('child_process').execSync(`pgrep -f "fabric-server-launch.jar" | head -1`).toString().trim()))), 'SIGKILL')
  assert(await wait(async () => !(await core.serverStatus(p.id)).running, 20), 'went down')
  assert(await wait(async () => (await core.serverStatus(p.id)).online, 120), 'auto restarted')
  core.serverStop(p.id)
  assert(await wait(async () => !(await core.serverStatus(p.id)).running, 30), 'stopped')
  await new Promise(r => setTimeout(r, 7000))
  assert(!(await core.serverStatus(p.id)).running, 'no restart after manual stop')
  fs.rmSync(path.join(tmp, 'profiles', p.id, 'server/world/level.dat'))
  await core.restoreBackup(p.id, name)
  assert(fs.existsSync(path.join(tmp, 'profiles', p.id, 'server/world/level.dat')), 'restored')
  console.log('ok', mods.length, 'server mods')
  process.exit(0)
})().catch(e => { console.error(e); process.exit(1) })
