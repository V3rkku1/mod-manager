// Live self-check against Thunderstore, Modrinth, Nexus (no key), GameBanana. Run: npm test
const assert = require('assert'), fs = require('fs'), os = require('os'), path = require('path')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mm-'))
const core = require('./core')(path.join(tmp, 'profiles'))
const count = dir => fs.existsSync(path.join(tmp, dir)) ? fs.readdirSync(path.join(tmp, dir)).length : 0
;(async () => {
  // Thunderstore + configs code (r2modman format)
  const ts = await core.createProfile({ name: 'LC', type: 'thunderstore', game: 'lethal-company', gameName: 'Lethal Company' })
  assert((await core.search(ts.id, 'thunderstore', 'LateCompany')).items.length, 'thunderstore search')
  const f = await core.filters(ts.id, 'thunderstore')
  const audio = f.categories.find(c => c.name === 'Audio')
  const all = await core.search(ts.id, 'thunderstore', ''), aud = await core.search(ts.id, 'thunderstore', '', 2, { categories: [audio.id] })
  assert(all.pages > aud.pages && aud.pages > 1 && aud.items.every(m => m.tags.includes('Audio')), 'category filter + pages')
  let p = await core.install(ts.id, 'thunderstore', 'notnotnotswipez-MoreCompany')
  assert(p.mods.some(m => m.id === 'BepInEx-BepInExPack'), 'dependency installed')
  assert(fs.existsSync(path.join(tmp, 'profiles', ts.id, 'files', p.mods.find(m => m.id === 'BepInEx-BepInExPack').stage, 'BepInEx/core/BepInEx.dll')), 'pack layout (own staging folder)')
  const d = await core.details(ts.id, 'thunderstore', 'notnotnotswipez-MoreCompany')
  assert(d.body.includes('More Company') && d.versions.length > 3, 'thunderstore details')
  await core.updateProfile(ts.id, { target: path.join(tmp, 'lc') })
  write(path.join(tmp, 'lc/BepInEx/config/test.cfg'), 'hello=1')
  const key = await core.exportR2(ts.id)
  const r2 = await core.importCode(key)
  assert.strictEqual(r2.profile.game, 'lethal-company')
  assert.strictEqual(r2.profile.mods.length, p.mods.length, 'r2 import mods')
  assert.deepStrictEqual(r2.profile.extra, ['BepInEx/config/test.cfg'], 'r2 import configs')
  await core.updateProfile(r2.profile.id, { target: path.join(tmp, 'lc2') })
  await core.deploy(r2.profile.id)
  assert.strictEqual(fs.readFileSync(path.join(tmp, 'lc2/BepInEx/config/test.cfg'), 'utf8'), 'hello=1', 'configs deployed')

  // Minecraft / Modrinth
  const mc = await core.createProfile({ name: 'MC', type: 'modrinth', mc: { version: '1.21.1', loader: 'fabric' } })
  assert((await core.search(mc.id, 'modrinth', 'sodium')).items.length, 'modrinth search')
  p = await core.install(mc.id, 'modrinth', 'mOgUt4GM') // Mod Menu, requires fabric-api
  assert(p.mods.length >= 2 && p.mods.every(m => m.files[0].startsWith('mods/')), 'modrinth install + deps')
  const code = await core.exportCode(mc.id)
  const { profile, failed } = await core.importCode(code)
  assert.deepStrictEqual(failed, [])
  assert.deepStrictEqual(profile.mods.map(m => m.vid).sort(), p.mods.map(m => m.vid).sort(), 'import matches')
  await assert.rejects(core.importCode('MM1garbage'), /Invalid share code/)

  await core.updateProfile(mc.id, { target: path.join(tmp, 'game') })
  write(path.join(tmp, 'game/config/x.json'), '{}')
  const file = path.join(tmp, 'pack.mmpack')
  assert.strictEqual(await core.exportFile(mc.id, file), 1, 'file has configs')
  const fromFile = await core.importFile(file)
  assert.deepStrictEqual(fromFile.profile.extra, ['config/x.json'])
  await core.deploy(mc.id)
  assert.strictEqual(count('game/mods'), p.mods.length, 'deploy')
  assert.deepStrictEqual(await core.checkUpdates(mc.id), {}, 'fresh install has no updates')
  // Failed version switch keeps the old mod and its files (regression: update used to delete first)
  const keep = (await core.listProfiles()).find(x => x.id === mc.id).mods.find(m => m.id === 'mOgUt4GM')
  await assert.rejects(core.install(mc.id, 'modrinth', 'mOgUt4GM', 'zzzzzzzz'))
  const after = (await core.listProfiles()).find(x => x.id === mc.id).mods.find(m => m.id === 'mOgUt4GM')
  assert(after && after.vid === keep.vid && fs.existsSync(path.join(tmp, 'profiles', mc.id, 'files', keep.stage || '', keep.files[0])), 'old version restored after failed update')
  // Snapshot + rollback
  const snap = await core.snapshot(mc.id, 'test')
  await core.install(mc.id, 'modrinth', 'gvQqBUqZ')
  const back = await core.restoreSnapshot(mc.id, snap)
  assert(!back.profile.mods.some(m => m.id === 'gvQqBUqZ') && back.profile.mods.some(m => m.id === 'mOgUt4GM'), 'rollback')
  assert((await core.snapshots(mc.id)).some(x => x.reason === 'Before rollback'), 'auto snapshot before rollback')
  // A corrupt profile.json no longer breaks the list
  fs.mkdirSync(path.join(tmp, 'profiles', 'broken'), { recursive: true }); fs.writeFileSync(path.join(tmp, 'profiles', 'broken', 'profile.json'), '{"id":')
  assert((await core.listProfiles()).length >= 2, 'list survives a broken profile')
  fs.rmSync(path.join(tmp, 'profiles', 'broken'), { recursive: true })
  const before = p.mods.length
  p = await core.update(mc.id, 'mOgUt4GM')
  assert.strictEqual(p.mods.length, before, 'update keeps mod')
  await core.setDisabled(mc.id, 'mOgUt4GM', true)
  await core.deploy(mc.id)
  assert.strictEqual(count('game/mods'), before - 1, 'disabled mod not deployed')
  await core.setAllDisabled(mc.id, true); await core.deploy(mc.id)
  assert.strictEqual(count('game/mods'), 0, 'disable all')
  await core.setAllDisabled(mc.id, false)
  // Pins, orphans, conflicts, preview/sync, vanilla deploy, crash helper
  await core.updateMod(mc.id, 'mOgUt4GM', { pinned: true, note: 'keep' })
  assert((await core.listProfiles()).find(x => x.id === mc.id).mods.find(m => m.id === 'mOgUt4GM').pinned, 'pin')
  assert.deepStrictEqual(await core.conflicts(mc.id), [], 'no conflicts')
  const other = await core.createProfile({ name: 'Other', type: 'modrinth', mc: { version: '1.21.1', loader: 'fabric' } })
  await core.install(other.id, 'modrinth', 'AANobbMI') // Sodium
  const pv = await core.preview(code, other.id)
  assert(pv.diff.add.includes('mOgUt4GM') && pv.diff.remove.includes('Sodium'), 'diff')
  const synced = (await core.sync(other.id, code, { remove: true })).profile
  assert.deepStrictEqual(synced.mods.map(m => m.vid).sort(), p.mods.map(m => m.vid).sort(), 'sync matches')
  await assert.rejects(core.sync(other.id, await core.exportCode(ts.id)), /different game/)
  await core.deploy(mc.id, { vanilla: true })
  assert.strictEqual(count('game/mods'), 0, 'vanilla deploy')
  assert((await core.listProfiles()).find(x => x.id === mc.id).mods.some(m => !m.disabled), 'vanilla keeps flags')
  write(path.join(tmp, 'game/crash-reports/crash-1.txt'), 'Description: Mod loading\nSuspected Mods: Mod Menu (modmenu)\nException')
  const cr = await core.analyzeCrash(mc.id)
  assert.deepStrictEqual(cr.suspects.map(m => m.name), ['Mod Menu'], 'crash suspects')
  await core.updateMod(mc.id, 'mOgUt4GM', { pinned: false })
  p = await core.uninstall(mc.id, 'mOgUt4GM')
  assert((await core.orphans(mc.id)).length >= 1, 'orphaned deps after removing parent')

  // Modrinth modpack (small fabric pack)
  const packs = await core.search(mc.id, 'modrinth', '', 1, { kind: 'modpack' })
  assert(packs.items.length, 'modpack search')

  // Nexus: search/details work without a key, install needs one
  const nx = await core.createProfile({ name: 'SDV', type: 'nexus', game: 'stardewvalley', gameId: '1303', gameName: 'Stardew Valley' })
  assert((await core.games('nexus', 'stardew')).some(g => g.id === 'stardewvalley'), 'nexus games')
  assert((await core.search(nx.id, 'nexus', 'automate')).items.some(m => m.id === '1063'), 'nexus search')
  assert((await core.details(nx.id, 'nexus', '1063')).versions.length, 'nexus details')
  await assert.rejects(core.install(nx.id, 'nexus', '1063'), /API key/)

  // GameBanana: install a real archive
  const gbGame = (await core.games('gamebanana', 'celeste')).find(g => g.name === 'Celeste')
  const gb = await core.createProfile({ name: 'Celeste', type: 'gamebanana', game: gbGame.id, gameName: 'Celeste' })
  const gbMods = await core.search(gb.id, 'gamebanana', '', 1, { sort: 'popular' })
  assert(gbMods.items.length && gbMods.pages > 1, 'gamebanana browse')
  const small = (await core.search(gb.id, 'gamebanana', 'skin')).items[0]
  p = await core.install(gb.id, 'gamebanana', small.id)
  assert(p.mods[0].files.length, 'gamebanana install')

  await assert.rejects(core.search(mc.id, 'curseforge', 'jei'), /CurseForge API key/)

  // Terraria: Workshop browse + enabled.json on deploy (download needs steamcmd on Windows)
  const tr = await core.createProfile({ name: 'T', type: 'terraria', game: 'terraria' })
  const ws = await core.search(tr.id, 'workshop', '', 1, { categories: ['Quality of Life'] })
  assert(ws.items.length && ws.pages > 1, 'workshop browse')
  assert((await core.details(tr.id, 'workshop', ws.items[0].id)).title, 'workshop details')
  write(path.join(tmp, 'CalamityMod.tmod'), 'x'); write(path.join(tmp, 'Off.tmod'), 'x')
  await core.addLocal(tr.id, [path.join(tmp, 'CalamityMod.tmod'), path.join(tmp, 'Off.tmod')])
  await core.setDisabled(tr.id, 'local:Off.tmod', true)
  await core.updateProfile(tr.id, { target: path.join(tmp, 'tml') }); await core.deploy(tr.id)
  assert.deepStrictEqual(JSON.parse(fs.readFileSync(path.join(tmp, 'tml/Mods/enabled.json'))), ['CalamityMod'], 'enabled.json')
  console.log('ok', code.length, 'char code, r2 key', key)
})().catch(e => { console.error(e); process.exitCode = 1 }).finally(() => fs.rmSync(tmp, { recursive: true, force: true }))

function write(f, s) { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s) }
