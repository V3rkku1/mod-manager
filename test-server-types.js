// Paper (Modrinth + Hangar plugins, Geyser), port conflict check, Bedrock Dedicated Server, backups. Run: npm run test:server
const assert = require('assert'), fs = require('fs'), path = require('path'), net = require('net')
const tmp = fs.mkdtempSync(path.join(require('os').tmpdir(), 'mm5-'))
const core = require('./core')(path.join(tmp, 'profiles'), { emit: () => {} })
const wait = async (fn, s = 180) => { for (let i = 0; i < s; i++) { if (await fn()) return true; await new Promise(r => setTimeout(r, 1000)) } return false }
;(async () => {
  const p = await core.createProfile({ name: 'Paper', type: 'modrinth', mc: { version: '1.21.1', loader: 'fabric' } })
  await core.setServerKind(p.id, 'paper')
  const mr = await core.pluginSearch(p.id, 'modrinth', 'luckperms'), hg = await core.pluginSearch(p.id, 'hangar', 'essentials')
  assert(mr.items.length && hg.items.length, 'plugin search')
  await core.pluginInstall(p.id, 'modrinth', mr.items[0].id)
  const ess = hg.items.find(x => /essentials/i.test(x.title))
  const pl = await core.pluginInstall(p.id, 'hangar', ess.id).catch(e => (console.log('hangar:', e.message), null))
  await core.serverStart(p.id, { eula: true, kind: 'paper', port: 25655, geyser: true, onStart: 'say started-by-scheduler' })
  assert(await wait(async () => (await core.serverStatus(p.id)).online, 300), 'paper online: ' + (await core.serverStatus(p.id)).log.slice(-6).join('\n'))
  await new Promise(r => setTimeout(r, 4000))
  const st = await core.serverStatus(p.id)
  assert(st.log.some(l => /started-by-scheduler/.test(l)), 'onStart command')
  assert(st.log.some(l => /LuckPerms/i.test(l)), 'plugin loaded')
  assert(st.log.some(l => /Geyser/i.test(l)), 'geyser plugin')
  const diag = await core.diagnostics(p.id)
  console.log(diag.map(d => `${d.ok ? 'OK ' : 'ERR'} ${d.name}: ${d.detail}`).join('\n'))
  // Port conflict -> clear error
  const p2 = await core.createProfile({ name: 'Clash', type: 'modrinth', mc: { version: '1.21.1', loader: 'vanilla' } })
  await assert.rejects(core.serverStart(p2.id, { eula: true, port: 25655 }), /used by another program/)
  core.serverStop(p.id); assert(await wait(async () => !(await core.serverStatus(p.id)).running, 40), 'paper stopped')
  // Bedrock
  const b = await core.createProfile({ name: 'Bedrock', type: 'modrinth', mc: { version: '1.21.1', loader: 'vanilla' } })
  await core.setServerKind(b.id, 'bedrock')
  await core.serverStart(b.id, { eula: true, kind: 'bedrock', port: 19140 })
  assert(await wait(async () => (await core.serverStatus(b.id)).online, 240), 'bedrock online: ' + (await core.serverStatus(b.id)).log.slice(-6).join('\n'))
  await core.setServerProps(b.id, { 'server-name': 'Friends' })
  const bk = await core.backup(b.id)
  core.serverStop(b.id); assert(await wait(async () => !(await core.serverStatus(b.id)).running, 40), 'bedrock stopped')
  await core.restoreBackup(b.id, bk)
  // Log analysis
  console.log('ok paper + bedrock', pl ? 'hangar ok' : 'hangar skipped')
  process.exit(0)
})().catch(e => { console.error(e); process.exit(1) })
